const _packSet = {...iconPack};

const _groups = {
  'collection': 'Collection',
  'commerce': 'Shopping',
  'delivery': 'Delivery',
  'grocery': 'Grocery',
  'logistics': 'Logistics',
  'mobility': 'Mobility',
  'navigation': 'Navigation',
  'ride': 'Ride',
  'safety': 'Safety',
  'transport': 'Transport',
  'ui-left': 'Interface',
  'ui-right': 'Interface',
};

/// What a slot stores for pack icon [name].
String packRef(String name) => 'pack:$name';

/// The pack icon a stored [value] names; null for anything else.
String? packRefName(Object? value) {
  if (value is! String) return null;
  final v = value.trim();
  if (!v.startsWith('pack:')) return null;
  final name = v.substring(5);
  return _packSet.contains(name) ? name : null;
}

/// The file of pack icon [name].
String packAsset(String name) => 'assets/icon_pack/$name.webp';

/// "ride-04-03" reads "Ride 4.3"; "ui-left-10-01" "Interface 10.1".
String packDisplayName(String name) {
  final m = RegExp(r'^(.*)-(\d+)-(\d+)$').firstMatch(name);
  if (m == null) return name;
  final group = _groups[m.group(1)] ?? m.group(1)!;
  return '$group ${int.parse(m.group(2)!)}.${int.parse(m.group(3)!)}';
}
